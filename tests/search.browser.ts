test('base path: distinct repeated paragraphs, query preservation, heading anchors and table/code targets', async ({ page }) => {
  await page.goto(fixture + '?source=test')
  await open(page)
  await find(page, '重复段落独特词')
  await page.getByRole('button', { name: /展开.*其余/ }).click()
  await expect(page.locator('.search-result')).toHaveCount(2)
  await page.locator('.search-result').nth(1).click()
  await expect(page.locator('.site-search-target')).toContainText('重复段落独特词')
  const firstTarget = await page.locator('.site-search-target').getAttribute('data-search-id')
  await expect(page).toHaveURL(/\?source=test#search-/)
  await open(page)
  await find(page, '重复段落独特词')
  await page.locator('.search-result').first().click()
  await expect(page.locator('.site-search-target')).not.toHaveAttribute('data-search-id', firstTarget!)
  for (const word of ['表格专用词', 'CodeOnlyToken', '列表专用词']) {
    await open(page)
    await find(page, word)
    await page.keyboard.press('Enter')
    await expect(page.locator('.site-search-target')).toContainText(word)
  }
  await page.goto(fixture + '#代码示例')
  await expect(page.locator('h2#代码示例')).toBeInViewport()
  await expect(page.locator('.site-search-target')).toHaveCount(0)
})

test('index failure retry, safe highlighting, clear and IME composition', async ({ page }) => {
  await page.route('**/search-index.json', route => route.fulfill({ status: 503, body: 'unavailable' }))
  await page.goto(fixture)
  await page.keyboard.press('Control+k')
  await expect(page.getByText('搜索索引加载失败，请检查网络后重试。')).toBeVisible()
  await page.unroute('**/search-index.json')
  await page.getByRole('button', { name: '重新加载' }).click()
  await find(page, 'onerror')
  await expect(page.locator('.search-result img')).toHaveCount(0)
  await expect(page.locator('.search-result mark')).toContainText('onerror')
  await page.getByRole('button', { name: '清空搜索内容' }).click()
  await expect(page.locator('.search-result')).toHaveCount(0)
  await query(page).dispatchEvent('compositionstart')
  await query(page).fill('无锡地铁')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.locator('.search-result')).toHaveCount(0)
  await query(page).dispatchEvent('compositionend')
  await expect(page.locator('.search-result').first()).toBeVisible()
})

test('editing exceptions, modal focus containment and focus/scroll restoration', async ({ page }) => {
  await page.goto(fixture)
  for (const label of ['普通输入框', '普通多行输入框', '普通选择框', '可编辑内容']) {
    await page.getByLabel(label).focus()
    await page.keyboard.press('Control+k')
    await expect(page.getByRole('dialog')).toHaveCount(0)
    // Dispatch Ctrl+F without opening Chrome's own find UI during automation.
    const prevented = await page.getByLabel(label).evaluate(element => {
      const event = new KeyboardEvent('keydown', { key: 'f', ctrlKey: true, bubbles: true, cancelable: true })
      element.dispatchEvent(event)
      return event.defaultPrevented
    })
    expect(prevented).toBe(false)
  }
  const launcher = page.getByRole('button', { name: '打开全站搜索' })
  await launcher.click()
  await expect(query(page)).toBeFocused()
  for (let i = 0; i < 9; i++) {
    await page.keyboard.press('Tab')
    expect(await page.evaluate(() => !!document.activeElement?.closest('dialog'))).toBe(true)
  }
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('hidden')
  await page.keyboard.press('Escape')
  await expect(launcher).toBeFocused()
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('')
})

